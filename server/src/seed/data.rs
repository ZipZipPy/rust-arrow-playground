//! Reference data for the mock orders: names, countries with real city
//! coordinates, categories with products and base prices.

pub struct Country {
    /// ISO 3166-1 alpha-2.
    pub code: &'static str,
    /// Relative share of customers.
    pub weight: u32,
    /// Largest city first; earlier cities get more customers.
    pub cities: &'static [City],
}

pub struct City {
    pub name: &'static str,
    pub latitude: f64,
    pub longitude: f64,
}

pub struct Category {
    pub name: &'static str,
    /// Relative share of orders.
    pub weight: u32,
    pub products: &'static [Product],
}

pub struct Product {
    pub name: &'static str,
    pub base_price: f64,
}

const fn city(name: &'static str, latitude: f64, longitude: f64) -> City {
    City {
        name,
        latitude,
        longitude,
    }
}

const fn product(name: &'static str, base_price: f64) -> Product {
    Product { name, base_price }
}

